"""The paper's proteins as a LaTeX table: accession, name, length and the experiments run on each.

    python supp_proteins.py CORPUS.json MOTIF_LEVELS.json UTR_CELLS.txt OUT.tex FASTA_DIR...

CORPUS.json is inputs/e2/corpus.json, whose `members` are the proteins of the Pareto-front
comparison, every one of which was also run without forbidden motifs. MOTIF_LEVELS.json is
E2's per-protein AUC table, whose `cell` entries are the proteins with a finished front at every
motif level. UTR_CELLS.txt lists the UTR experiment's cells, a protein on a UTR pair, as
inputs/e3/cells.txt does. Each protein's <protein>.fasta is looked up in the FASTA_DIRs in order.

The name is the header's own: a UniProt header's protein name without the organism and gene
fields, and for the sequences that are not UniProt entries the description their header gives.
A header that carries no description gets its name from NAMES. Rows are ordered by length.
"""
import json
import os
import re
import sys

TEX = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_"}
# Headers that are a bare identifier.
NAMES = {
    "P0DTC2": "Spike glycoprotein (SARS-CoV-2)",
    **{f"PRT-0{i}": "Cas ortholog" for i in range(3, 8)},
}
# The accession a sequence actually is, where the label it was run under names another entry.
# The runs were filed under the label, which the frozen result deposits still carry in their
# file names, so the rename happens here, at the one place a reader sees an accession.
RENAMED = {"P01707": "P01706"}
MARK = r"$\checkmark$"


def tex(text):
    for ch, sub in TEX.items():
        text = text.replace(ch, sub)
    return text


def read(path):
    with open(path) as f:
        header = f.readline().strip().lstrip(">")
        residues = sum(len(line.strip().rstrip("*")) for line in f)
    return header, residues


def describe(label, header):
    """The protein's name and its residue range, if the entry is a part of another protein."""
    if label in NAMES:
        return NAMES[label]
    m = re.match(r"sp\|(\w+)\|\S+ (.+?) OS=", header)
    if m:
        assert m.group(1) == label, (label, header)
        return m.group(2)
    rest = header.split(" ", 1)[1]
    rest = re.sub(r", \d+ aa$", "", rest)
    m = re.match(r"(.+), (\w+) (\d+)-(\d+)$", rest)
    if m:
        return f"{m.group(1)}, residues {m.group(3)} to {m.group(4)} of {m.group(2)}"
    return rest[:1].upper() + rest[1:]


def find(protein, dirs):
    for d in dirs:
        path = os.path.join(d, f"{protein}.fasta")
        if os.path.exists(path):
            return path
    raise FileNotFoundError(f"{protein}.fasta in none of {dirs}")


def write(out, rows, n_front, n_motif, n_utr):
    caption = (
        f"\\textbf{{Proteins.}} The ${n_front}$ proteins of the Pareto-front comparison "
        f"(\\cref{{sec:res-front}}), ordered by length. Every protein was also run with "
        f"$\\mc{{M}} = \\emptyset$ (\\cref{{sec:res-motifs}}). Motifs marks the ${n_motif}$ "
        f"proteins whose fronts are finished at every motif level, and UTRs the ${n_utr}$ "
        f"proteins of the UTR experiment, each designed with each of the five UTR pairs "
        f"(\\cref{{sec:res-utr}})."
    )
    with open(out, "w") as f:
        f.write("% Generated by pipelines/scripts/supp_proteins.py -- do not edit.\n")
        f.write("{\\footnotesize\n\\begin{longtable}{lp{0.5\\linewidth}rccc}\n")
        f.write(f"\\caption{{{caption}}}\n\\label{{tab:proteins}}\\\\\n")
        head = "\\hline\nProtein & Name & Residues & Front & Motifs & UTRs \\\\\n\\hline\n"
        f.write(head + "\\endfirsthead\n")
        f.write("\\multicolumn{6}{l}{\\cref{tab:proteins}, continued} \\\\\n" + head + "\\endhead\n")
        f.write("\\hline\n\\endfoot\n")
        for residues, p, name, motif, utr in rows:
            marks = " & ".join(MARK if x else "" for x in (True, motif, utr))
            count = f"{residues:,}".replace(",", "{,}")
            f.write(f"{tex(p)} & {tex(name)} & {count} & {marks} \\\\\n")
        f.write("\\end{longtable}\n}\n")


def main():
    corpus, levels, cells, out, *dirs = sys.argv[1:]
    rename = RENAMED.get
    proteins = [rename(p, p) for p in json.load(open(corpus))["members"]]
    motif = {rename(x["cell"], x["cell"]) for x in json.load(open(levels))}
    utr = {rename(c, c) for c in (line.split()[0].split("__")[0] for line in open(cells) if line.strip())}
    assert motif <= set(proteins), sorted(motif - set(proteins))
    assert utr <= set(proteins), sorted(utr - set(proteins))
    rows = []
    for p in proteins:
        header, residues = read(find(p, dirs))
        rows.append((residues, p, describe(p, header), p in motif, p in utr))
    rows.sort()
    write(out, rows, len(rows), len(motif), len(utr))
    print(f"{len(rows)} proteins, {rows[0][0]} to {rows[-1][0]} residues; "
          f"{len(motif)} at every motif level, {len(utr)} in the UTR experiment")


if __name__ == "__main__":
    main()
