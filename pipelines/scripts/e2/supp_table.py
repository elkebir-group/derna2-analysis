"""The motif catalog as a LaTeX table: set, name, sequence, effect, and what each one costs.

    E2_DEPOSIT=... E2_MOTIF_DIR=... E2_SUPP=... python supp_table.py OUT_TEX

The supplement plate labels panel (d) by name, because a name-over-sequence tick cannot fit
there: a rotated label's footprint across the axis is its height, and 24 of them are the
densest type on the plate. The sequences live here instead, at full size, with the
per-motif counts the panel draws so a reader can read a value rather than measure a bar.

Rows are grouped by set and ordered within a set as the set file lists them, which is the
order the levels add them, not by any quantity measured here. The set and the effect are
printed only where they change, so a run of motifs sharing one names it once.

Two columns are editorial rather than measured -- the display name and the effect -- and
both are read from committed files under the motif directory, declared as inputs of the
rule that writes this table. Neither is written into this script.
"""

import json
import os
import sys

import supp_common as common

OUT_TEX = sys.argv[1] if len(sys.argv) > 1 else f"{common.OUT}/motif_table.tex"
EFFECTS_JSON = os.environ.get("E2_MOTIF_EFFECTS", f"{common.MOTIF_DIR}/effects.json")
SETNAME = {"I": r"$\mc{M}_{\mr{I}}$",
           "II": r"$\mc{M}_{\mr{II}}$",
           "III": r"$\mc{M}_{\mr{III}}$"}


# What a name or an effect may contain that LaTeX would not print as written. The prime in
# "5' splice" is the live case: pdflatex dropped it silently and the table read "5 splice".
TEX = {"\u2032": "$'$", "&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_"}


def tex(text):
    """A field as LaTeX, refusing anything this does not know how to print."""
    for ch, sub in TEX.items():
        text = text.replace(ch, sub)
    assert text.isascii(), f"no LaTeX spelling for {text!r}"
    return text


def effects():
    """{pattern (U-spelled): what the motif does}, keyed as the set files spell it."""
    raw = json.load(open(EFFECTS_JSON))
    return {k.replace("T", "U"): v for k, v in raw.items() if not k.startswith("_")}


def body(motifs, counts, names, effect, n_prot):
    """One row per motif, with the set and the effect named only where they change."""
    out, seen_set, seen_effect = [], None, None
    for i, (s, m) in enumerate(motifs):
        label = "" if s == seen_set else SETNAME[s]
        if s != seen_set:
            seen_effect = None
        shown = "" if effect[m] == seen_effect else effect[m]
        seen_set, seen_effect = s, effect[m]
        out.append(f"{label} & {tex(names[m])} & \\texttt{{{m}}} & {tex(shown)} & "
                   f"{counts[m]} of {n_prot} \\\\")
        if i + 1 == len(motifs) or motifs[i + 1][0] != s:
            out.append(r"\hline")
    return out


def main():
    adm = json.load(open(f"{common.OUT}/admits.json"))
    motifs = [tuple(sm) for sm in adm["motifs"]]
    names, effect = common.names(), effects()
    n_prot = len(adm["rows"])
    counts = {m: sum(1 for r in adm["rows"] if not r["admits"][m]) for _, m in motifs}
    # Both maps are over the parsed set, so a motif missing from either is a mismatch
    # between the motif files and the file that names them, not something to paper over.
    for what, table in (("display name", names), ("effect", effect)):
        missing = [m for _, m in motifs if m not in table]
        assert not missing, f"no {what} for {missing}"

    lines = [r"\begin{table}[h]", r"\centering",
             r"\caption{\textbf{Forbidden motifs.} "
             r"Sequences are 5$'$ to 3$'$, with R denoting A or G and `rc' denoting "
             r"reverse complement. "
             r"A motif is \emph{inadmissible} for a protein when no synonymous coding "
             r"sequence of that protein contains it, so forbidding it there removes no "
             rf"design; the last column counts those proteins among the {n_prot} with a "
             r"$\mc{M} = \emptyset$ front, and is what \cref{fig:supp-motif}d draws.}",
             r"\label{tab:motifs}",
             r"\begin{tabular}{lllll}", r"\hline",
             r"Set & Motif & Sequence & Effect & Inadmissible for \\", r"\hline"]
    lines += body(motifs, counts, names, effect, n_prot)
    lines += [r"\end{tabular}", r"\end{table}"]

    os.makedirs(os.path.dirname(os.path.abspath(OUT_TEX)), exist_ok=True)
    with open(OUT_TEX, "w") as fh:
        fh.write("% Generated by pipelines/scripts/e2/supp_table.py -- do not edit.\n")
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_TEX}: {len(motifs)} motifs over {n_prot} proteins")


if __name__ == "__main__":
    sys.exit(main())
